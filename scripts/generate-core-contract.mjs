import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { contract, schemas } from '../contracts/core-v0.1.mjs';

// This generator deliberately supports only the schema constructs used in the
// contract. Unsupported constructs fail loudly instead of silently emitting any.
function typeOf(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.oneOf || schema.anyOf)
    return (schema.oneOf ?? schema.anyOf)
      .map((item) => `(${typeOf(item)})`)
      .join(' | ');
  switch (schema.type) {
    case 'null':
      return 'null';
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      return `Array<${typeOf(schema.items)}>`;
    case 'object':
      return `{\n${Object.entries(schema.properties)
        .map(
          ([name, value]) =>
            `  ${JSON.stringify(name)}${schema.required.includes(name) ? '' : '?'}: ${typeOf(value)};`,
        )
        .join('\n')}\n}`;
    default:
      throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`);
  }
}

export const generated = [
  ['../contracts/openapi.v0.1.json', `${JSON.stringify(contract, null, 2)}\n`],
  [
    '../lib/api/types.generated.ts',
    `// Generated by pnpm contracts:generate from contracts/core-v0.1.mjs.\n// JSON Schema performs runtime validation; TypeScript alone does not validate JSON.\n\n${Object.entries(
      schemas,
    )
      .map(([name, schema]) => `export type ${name} = ${typeOf(schema)};`)
      .join('\n\n')}\n`,
  ],
];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  for (const [relative, content] of generated) {
    const path = new URL(relative, import.meta.url);
    if (check) {
      if ((await readFile(path, 'utf8')) !== content)
        throw new Error(`Generated contract is stale: ${path.pathname}`);
    } else {
      await mkdir(new URL('.', path), { recursive: true });
      await writeFile(path, content);
    }
  }
  process.stdout.write(
    check
      ? 'Generated contract is current.\n'
      : 'Generated OpenAPI and TypeScript contract.\n',
  );
}
