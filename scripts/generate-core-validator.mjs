import { readFile, writeFile } from 'node:fs/promises';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createContractValidator } from './core-validator.mjs';

const names = [
  'Id',
  'PortsPage',
  'PortResource',
  'CandidateResource',
  'CandidateMutation',
  'WorkspaceSnapshot',
  'ValidationRequest',
  'ValidationResource',
  'JobResource',
  'StartSafeApplyRequest',
  'TransactionResource',
  'RequestRecord',
  'Problem',
];
const ajv = createContractValidator();
const raw = standaloneCode(
  ajv,
  Object.fromEntries(
    names.map((name) => [name, `#/components/schemas/${name}`]),
  ),
);
// Standalone Ajv format/Unicode helpers use require even in ESM output. Bind
// the exact installed helpers as ESM imports for browsers and Workers (no eval).
const helpers = [...raw.matchAll(/require\("([^"]+)"\)/g)].map(
  (match) => match[1],
);
const unique = [...new Set(helpers)];
for (const helper of unique)
  if (
    !['ajv-formats/dist/formats', 'ajv/dist/runtime/ucs2length'].includes(
      helper,
    )
  )
    throw new Error(`Unreviewed generated runtime import: ${helper}`);
let body = raw;
unique.forEach((helper, i) => {
  body = body.replaceAll(`require("${helper}")`, `runtime${i}`);
});
const imports = unique
  .map((helper, i) => `import runtime${i} from '${helper}.js';`)
  .join('\n');
const source = `// Generated contract validator; regenerate with pnpm contracts:generate.\n${imports}\n${body}\nexport const validators = { ${names.join(', ')} };\nexport function validateContract(name, value) { return Object.hasOwn(validators, name) && validators[name](value); }\n`;
const file = new URL('../lib/api/validator.generated.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(file, 'utf8')) !== source)
    throw new Error('Generated browser validator is stale.');
} else await writeFile(file, source);
const declaration = new URL(
  '../lib/api/validator.generated.d.mts',
  import.meta.url,
);
const signature = `// Generated by pnpm contracts:generate.\nimport type { HttpSchemas } from './http-client';\nexport function validateContract(name: keyof HttpSchemas, value: unknown): boolean;\nexport const validators: Record<keyof HttpSchemas, (value: unknown) => boolean>;\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(declaration, 'utf8')) !== signature)
    throw new Error('Generated validator declaration is stale.');
} else await writeFile(declaration, signature);
process.stdout.write('Browser contract validator is current.\n');
