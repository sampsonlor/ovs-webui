import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { api, pagePaths, scopePaths } from '../contracts/public-v1.mjs';
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
function output(path, text) {
 const file = fileURLToPath(new URL(path, root));
 if (check) assert.equal(readFileSync(file, 'utf8').replaceAll('\r\n', '\n'), text, `${path}: regenerate public contract`);
 else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, text); }
}
const serialized = JSON.stringify(api, null, 2) + '\n';
output('contracts/v1.openapi.json', serialized);
output('internal/apicontract/openapi.json', serialized);
const trace = JSON.parse(readFileSync(new URL('docs/implementation/phase1-traceability.v0.1.json', root)));
const coverage = { contract_version: api.info.version, scope: [], pages: [] };
for (const [rows, mappings, target] of [[trace.scope_requirements, scopePaths, coverage.scope], [trace.pages, pagePaths, coverage.pages]]) {
 assert.equal(rows.length, Object.keys(mappings).length);
 for (const row of rows) {
  const paths = mappings[row.id]; assert.ok(paths?.length, row.id);
  const operations = paths.flatMap(path => { assert.ok(api.paths[path], path); return Object.values(api.paths[path]).map(op => op.operationId); });
  target.push({ id: row.id, name: row.name, paths, operations, status: 'transport-contract; service acceptance remains with linked engineering issue' });
 }
}
output('contracts/v1.coverage.json', JSON.stringify(coverage, null, 2) + '\n');

function ts(schema) {
 if (schema.$ref) return schema.$ref.split('/').at(-1);
 if (schema.const !== undefined) return JSON.stringify(schema.const);
 if (schema.enum) return schema.enum.map(JSON.stringify).join(' | ');
 if (schema.oneOf || schema.anyOf) return `(${(schema.oneOf ?? schema.anyOf).map(ts).join(' | ')})`;
 if (schema.allOf) return `(${schema.allOf.map(ts).join(' & ')})`;
 if (Array.isArray(schema.type)) return schema.type.map(type => ts({ ...schema, type })).join(' | ');
 if (schema.type === 'object') {
  const props = Object.entries(schema.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${ts(value)}`).join('; ');
  const extra = schema.additionalProperties === false ? '' : `${props ? '; ' : ''}[key: string]: ${typeof schema.additionalProperties === 'object' ? ts(schema.additionalProperties) : 'unknown'}`;
  return `{ ${props}${extra} }`;
 }
 if (schema.type === 'array') return `Array<${ts(schema.items ?? {})}>`;
 return ({ string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' })[schema.type] ?? 'unknown';
}
let typescript = '// Generated by scripts/generate-public-contract.mjs; preserve unknown response fields/states.\n';
for (const [name, schema] of Object.entries(api.components.schemas)) typescript += `export type ${name} = ${ts(schema)};\n`;
typescript += 'export interface Operations {\n';
for (const [path, methods] of Object.entries(api.paths)) for (const [method, op] of Object.entries(methods)) {
 const body = op.requestBody?.content['application/json'].schema;
 const responses = Object.entries(op.responses).filter(([code]) => Number(code) < 300).map(([, response]) => response.content?.['application/json']?.schema).filter(Boolean);
 typescript += `  ${op.operationId}: { method: ${JSON.stringify(method.toUpperCase())}; path: ${JSON.stringify(path)}; body: ${body ? ts(body) : 'never'}; response: ${responses.length ? responses.map(ts).join(' | ') : 'void'} };\n`;
}
typescript += '}\n';
output('clients/typescript/public-v1.generated.ts', typescript);

const goName = value => value.split(/[_-]/).map(part => part[0].toUpperCase() + part.slice(1)).join('');
function go(schema) {
 if (schema.$ref) return schema.$ref.split('/').at(-1);
 if (schema.oneOf || schema.anyOf || schema.allOf || Array.isArray(schema.type)) return 'json.RawMessage';
 if (schema.type === 'array') return '[]' + go(schema.items ?? {});
 if (schema.type === 'object') return 'map[string]json.RawMessage';
 return ({ string: 'string', integer: 'int64', number: 'float64', boolean: 'bool' })[schema.type] ?? 'json.RawMessage';
}
let golang = '// Code generated by scripts/generate-public-contract.mjs; DO NOT EDIT.\npackage apidto\nimport "encoding/json"\n';
for (const [name, schema] of Object.entries(api.components.schemas)) {
 if (schema.type !== 'object' || !schema.properties) { const value = go(schema); golang += `type ${name} ${value === 'json.RawMessage' ? '= ' : ''}${value}\n`; continue; }
 const extensible = schema.additionalProperties !== false;
 golang += `type ${name} struct {\n`;
 for (const [field, value] of Object.entries(schema.properties)) golang += `${goName(field)} ${go(value)} \`json:"${field}${schema.required?.includes(field) ? '' : ',omitempty'}"\`\n`;
 if (extensible) golang += 'ExtraFields map[string]json.RawMessage `json:"-"`\n';
 golang += '}\n';
 if (extensible) {
  golang += `func (v *${name}) UnmarshalJSON(data []byte) error { type plain ${name}; return decodeOpen(data,(*plain)(v),&v.ExtraFields) }\n`;
  golang += `func (v ${name}) MarshalJSON() ([]byte,error) { type plain ${name}; return encodeOpen(plain(v),v.ExtraFields) }\n`;
 }
}
golang = execFileSync('gofmt', { input: golang, encoding: 'utf8' }).replaceAll('\r\n', '\n');
output('internal/apidto/public_v1_generated.go', golang);
console.log(`Public v1: ${Object.keys(api.paths).length} paths, ${coverage.scope.length} Scope IDs, ${coverage.pages.length} pages; generated artifacts ${check ? 'verified' : 'written'}`);
